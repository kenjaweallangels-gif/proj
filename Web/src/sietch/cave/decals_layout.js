// Раскладка декалей — три слоя истории в стенах пещеры (docs/lore/world_bible.md §4):
//   слой 1 — фрименская резьба (carving/carvingB) и отпечатки ладоней (hands, самые древние/самые свежие),
//   слой 2 — печати Квизарата (sigil), вырубленные ПОВЕРХ резьбы (частично перекрывают её),
//   слой 3 — наивные росписи возрожденцев (mural), детский мел (chalk), охра/киноварь ладоней.
// Лучевая постановка: o — точка в воздухе, d — направление на стену; w×h — метры; rot — поворот; nx/ny — сетка проекции.
import { NICHES, SHELF_BAYS, BAY, CELLAR, EXIT } from './layout.js';
export const DECALS = [];
const D = (tex, layer, o, d, w, h, extra = {}) => DECALS.push({ tex, layer, o, d, w, h, ...extra });
const N = [0, 0, -1], S = [0, 0, 1], E = [1, 0, 0], W = [-1, 0, 0];

// ---------------------------------------------------------------- B1: шлюз ----
D('carving', 1, [3.0, 1.9, 0.0], N, 1.7, 1.7);
D('hands', 1, [5.2, 1.5, 0.0], S, 1.5, 0.75);
D('carving', 1, [11.5, 1.7, 0.0], S, 1.8, 1.8);
D('sigil', 2, [12.4, 2.25, 0.0], S, 1.15, 1.15, { rot: 0.08 });            // печать поверх резьбы
D('carvingB', 1, [17.0, 1.7, 0.0], N, 1.8, 1.8);
D('mural', 3, [21.0, 1.4, 0.0], S, 1.7, 0.85, { rot: -0.04 });
D('chalk', 3, [20.4, 0.75, 0.0], N, 1.6, 0.8);
D('sigil', 2, [27.0, 2.1, 0.8], N, 1.5, 1.5);
D('carving', 1, [26.2, 1.9, 0.8], N, 1.8, 1.8, { rot: 0.1 });
D('carving', 1, [30.5, 1.8, 0.8], S, 1.8, 1.8);
D('hands', 3, [10.2, 1.3, 0.0], N, 1.5, 0.75);
D('hands', 1, [22.7, 1.45, 0.0], S, 1.5, 0.75);
D('mural', 3, [34.0, 1.5, 0.0], S, 2.0, 1.0);

// ---------------------------------------------------------------- B2: галерея ----
// Резьба и печати на «столбах» между нишами нижнего яруса.
[58, 64, 70, 76.5, 83, 89, 95].forEach((x, i) => {
  D('carving', 1, [x, 2.2, 0], N, 1.35, 1.35, { rot: (i % 3 - 1) * 0.04 });
  D('carvingB', 1, [x + 0.3, 2.3, 0], S, 1.35, 1.35);
  if (i % 2 === 0) D('sigil', 2, [x + 0.15, 3.9, 0], N, 1.15, 1.15);
  else D('sigil', 2, [x - 0.1, 3.9, 0], S, 1.1, 1.1);
});
// Росписи возрожденцев на дальней стене карниза.
D('mural', 3, [70, 8.1, 6.4], S, 5.8, 2.9);
D('mural', 3, [64, 8.0, -6.4], N, 4.8, 2.4);
D('carving', 1, [58, 8.0, 6.4], S, 2.0, 2.0);
D('sigil', 2, [58.8, 8.6, 6.4], S, 1.5, 1.5);
D('carving', 1, [78, 8.0, -6.4], N, 2.0, 2.0);
D('sigil', 2, [83, 8.3, 6.4], S, 1.6, 1.6);
D('hands', 3, [90, 7.6, 6.4], S, 1.6, 0.8);
// Входная стена галереи (запад): знак Квизарата над проходом.
D('sigil', 2, [46, 6.0, 0], W, 2.2, 2.2, { maxT: 12 });
D('hands', 1, [46, 2.2, 3.4], W, 1.5, 0.75, { maxT: 12 });
// Детский мел и ладони у подножия лестниц.
D('chalk', 3, [44.5, 1.0, 3.2], S, 3.2, 1.6);
D('chalk', 3, [45.5, 1.0, -3.2], N, 3.0, 1.5);
D('hands', 3, [43.0, 1.2, 5.0], S, 1.5, 0.75);
D('hands', 1, [43.0, 1.2, -5.0], N, 1.5, 0.75);

// ---------------------------------------------------------------- B3: проходы ----
D('carving', 1, [120, 1.7, 0.7], N, 1.5, 1.5);
D('carvingB', 1, [140, 1.7, -0.3], N, 1.5, 1.5);
D('sigil', 2, [131, 1.9, 0.3], S, 1.1, 1.1);
D('mural', 3, [112, 1.6, -0.6], N, 1.5, 0.8);
D('hands', 1, [104, 1.4, 0.5], S, 1.4, 0.7);
D('carving', 1, [110, 1.6, -7.6], N, 1.4, 1.4);
D('carving', 1, [125, 1.7, -15.2], N, 1.4, 1.4);
D('carving', 1, [108, 1.5, 3.0], S, 0.9, 0.9);   // святилище Шианы: старая резьба под лентой
D('hands', 3, [108, 1.0, 2.6], S, 1.2, 0.6);

// ---------------------------------------------------------------- B4: цистерна ----
D('carving', 1, [125, 3.4, 22], S, 3.0, 3.0);
D('carvingB', 1, [135, 3.4, 22], S, 3.0, 3.0);
D('sigil', 2, [130, 4.4, 22], S, 2.0, 2.0);
D('carvingB', 1, [118, 3.3, 18], W, 3.0, 3.0);
D('sigil', 2, [132, 4.0, 18], E, 2.2, 2.2);

// ---------------------------------------------------------------- B5: зал ----
for (let i = 0; i < 8; i++) {
  const x = 154 + i * 6 + 3;
  for (const [sg, dir] of [[-1, N], [1, S]]) {
    D(i % 3 === 1 ? 'carvingB' : 'carving', 1, [x, 3.0, sg * 6], dir, 2.2, 2.2, { rot: ((i * 7) % 5 - 2) * 0.03, maxT: 22 });
    if (i % 2 === 0) D('sigil', 2, [x + 0.4, 5.9, sg * 6], dir, 2.0, 2.0, { maxT: 22 });
    else D('mural', 3, [x, 6.0, sg * 6], dir, 2.8, 1.4, { maxT: 22 });
  }
}
D('hands', 3, [170, 1.6, 8], S, 1.8, 0.9, { maxT: 22 });
D('hands', 1, [182, 1.6, -8], N, 1.8, 0.9, { maxT: 22 });
D('carving', 1, [192, 5.8, -6], E, 2.2, 2.2, { maxT: 20 });
D('carving', 1, [192, 5.8, 6], E, 2.2, 2.2, { maxT: 20 });
D('sigil', 2, [190, 10.0, 0], E, 3.4, 3.4, { maxT: 20 });

// ---------------------------------------------------------------- жилые комнаты B3 (семейные): мел детей, роспись, старая резьба ----
for (const n of NICHES) {
  if (n.kind === 'shrine') continue;
  D('mural', 3, [n.xc, 1.7, n.zc], [0, 0, n.side], 1.7, 0.9, { maxT: 9 });
  D('chalk', 3, [n.xc - 1.5, 0.8, n.zc], W, 1.5, 0.75, { maxT: 6 });
  D('carving', 1, [n.xc + 1.4, 1.5, n.zc + n.side * 0.5], E, 1.2, 1.2, { maxT: 6 });
  if (n.rz > 2.5) D('hands', 3, [n.xc - 1.0, 1.1, n.zc + n.side * 1.2], W, 1.3, 0.65, { maxT: 6 });
}

// ---------------------------------------------------------------- спальные эркеры карниза B2 ----
SHELF_BAYS.forEach((x, i) => {
  for (const s of [-1, 1]) {
    const bx = x + (s > 0 ? 1 : 0);
    D(i % 2 ? 'mural' : 'chalk', 3, [bx, BAY.cy + 0.2, s * (BAY.cz - 0.6)], [0, 0, s], i % 2 ? 1.8 : 1.5, i % 2 ? 0.9 : 0.75, { maxT: 8 });
    D('hands', 1, [bx - 1.2, BAY.cy - 0.6, s * (BAY.cz - 0.6)], [0, 0, s], 1.2, 0.6, { maxT: 8 });
  }
});

// ---------------------------------------------------------------- B6: водяной погреб ----
{
  const F = CELLAR.floorY;
  // «Книги долгов» между нишами-кладовыми на длинных стенах нефа
  for (const x of [118.5, 124.5, 130.5, 136.5]) {
    D('tally', 1, [x, -6.4, 37], [0, 0, 1], 2.2, 1.65, { maxT: 14 });
    D('tally', 1, [x, -6.4, 37], [0, 0, -1], 2.2, 1.65, { maxT: 14 });
  }
  D('sigil', 2, [112.2, -6.2, 33.0], [0, 0, -1], 1.6, 1.6, { maxT: 8 });        // печать Квизарата у входа (сбита, поверх старой резьбы)
  D('carving', 1, [112.2, -6.4, 41.0], [0, 0, 1], 1.8, 1.8, { maxT: 8 });
  D('tally', 3, [101.6, -6.0, 31.2], [-1, 0, 0], 2.4, 1.8, { maxT: 8 });          // свежий счёт у лестницы
  D('carving', 1, [146.5, -6.8, 37], [1, 0, 0], 2.6, 2.6, { maxT: 8 });           // станция измерения: резьба «Дар воды»
  D('hands', 1, [146.5, -7.8, 35.0], [1, 0, 0], 1.6, 0.8, { maxT: 8 });
  D('tally', 3, [146.5, -6.6, 39.4], [1, 0, 0], 1.8, 1.35, { maxT: 8 });
  // лестница: ладони и мел
  D('hands', 1, [101.3, -2.8, 18], [-1, 0, 0], 1.4, 0.7, { maxT: 4 });
  D('chalk', 3, [101.3, -4.4, 22], [1, 0, 0], 1.4, 0.7, { maxT: 4 });
  D('hands', 3, [101.3, -6.4, 26.5], [-1, 0, 0], 1.3, 0.65, { maxT: 4 });
}

// ---------------------------------------------------------------- выходной туннель в сад: следы тех, кто ходил поливать ----
[10, 22, 34, 47, 60].forEach((i, k) => {
  const n = EXIT.nodes[i], n2 = EXIT.nodes[i + 1];
  const dx = n2[0] - n[0], dz = n2[1] - n[1], l = Math.hypot(dx, dz), px = -dz / l, pz = dx / l, sg = k % 2 ? 1 : -1;
  D(k % 3 === 0 ? 'carving' : k % 3 === 1 ? 'hands' : 'chalk', k % 3 === 0 ? 1 : 3, [n[0], EXIT.ys[i] + 1.5, n[1]], [px * sg, 0, pz * sg], k % 3 === 0 ? 1.5 : 1.3, k % 3 === 0 ? 1.5 : 0.65, { maxT: 4 });
});
