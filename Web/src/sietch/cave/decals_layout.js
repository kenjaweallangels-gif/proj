// Раскладка декалей — три слоя истории в стенах пещеры (docs/lore/world_bible.md §4):
//   слой 1 — фрименская резьба (carving/carvingB) и отпечатки ладоней (hands, самые древние/самые свежие),
//   слой 2 — печати Квизарата (sigil), вырубленные ПОВЕРХ резьбы (частично перекрывают её),
//   слой 3 — наивные росписи возрожденцев (mural), детский мел (chalk), охра/киноварь ладоней.
// Лучевая постановка: o — точка в воздухе, d — направление на стену; w×h — метры; rot — поворот; nx/ny — сетка проекции.
export const DECALS = [];
const D = (tex, layer, o, d, w, h, extra = {}) => DECALS.push({ tex, layer, o, d, w, h, ...extra });
const N = [0, 0, -1], S = [0, 0, 1], E = [1, 0, 0], W = [-1, 0, 0];

// ---------------------------------------------------------------- B1: шлюз ----
D('carving', 1, [3.0, 1.9, 0.0], N, 1.7, 1.7);
D('hands', 1, [5.2, 1.5, 0.0], S, 1.5, 0.75);
