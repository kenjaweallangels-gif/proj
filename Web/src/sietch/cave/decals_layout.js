D('sigil', 2, [12.4, 2.25, 0.0], S, 1.15, 1.15, { rot: 0.08 });            // печать поверх резьбы
D('carvingB', 1, [17.0, 1.7, 0.0], N, 1.8, 1.8);
D('mural', 3, [21.0, 1.4, 0.0], S, 1.7, 0.85, { rot: -0.04 });
D('chalk', 3, [20.4, 0.75, 0.0], N, 1.6, 0.8);
D('sigil', 2, [27.0, 2.1, 0.8], N, 1.5, 1.5);
D('carving', 1, [26.2, 1.9, 0.8], N, 1.8, 1.8, { rot: 0.1 });
D('carving', 1, [30.5, 1.8, 0.8], S, 1.8, 1.8);
D('hands', 3, [10.2, 1.3, 0.0], N, 1.5, 0.75);
D('hands', 1, [22.7, 1.45, 0.0], S, 1.5, 0.75);
D('mural', 3, [34.0, 1.5, 0.0], S, 2.0, 1.0);

// ---------------------------------------------------------------- B2: галерея ----
// Резьба и печати на «столбах» между нишами нижнего яруса.
[58, 64, 70, 76.5, 83, 89, 95].forEach((x, i) => {
  D('carving', 1, [x, 2.2, 0], N, 1.35, 1.35, { rot: (i % 3 - 1) * 0.04 });
  D('carvingB', 1, [x + 0.3, 2.3, 0], S, 1.35, 1.35);
  if (i % 2 === 0) D('sigil', 2, [x + 0.15, 3.9, 0], N, 1.15, 1.15);
  else D('sigil', 2, [x - 0.1, 3.9, 0], S, 1.1, 1.1);
});
// Росписи возрожденцев на дальней стене карниза.
D('mural', 3, [70, 8.1, 6.4], S, 5.8, 2.9);
D('mural', 3, [64, 8.0, -6.4], N, 4.8, 2.4);
D('carving', 1, [58, 8.0, 6.4], S, 2.0, 2.0);
D('sigil', 2, [58.8, 8.6, 6.4], S, 1.5, 1.5);
D('carving', 1, [78, 8.0, -6.4], N, 2.0, 2.0);
D('sigil', 2, [83, 8.3, 6.4], S, 1.6, 1.6);
D('hands', 3, [90, 7.6, 6.4], S, 1.6, 0.8);
// Входная стена галереи (запад): знак Квизарата над проходом.
D('sigil', 2, [46, 6.0, 0], W, 2.2, 2.2, { maxT: 12 });
D('hands', 1, [46, 2.2, 3.4], W, 1.5, 0.75, { maxT: 12 });
// Детский мел и ладони у подножия лестниц.
D('chalk', 3, [44.5, 1.0, 3.2], S, 3.2, 1.6);
D('chalk', 3, [45.5, 1.0, -3.2], N, 3.0, 1.5);
D('hands', 3, [43.0, 1.2, 5.0], S, 1.5, 0.75);
D('hands', 1, [43.0, 1.2, -5.0], N, 1.5, 0.75);

// ---------------------------------------------------------------- B3: проходы ----
D('carving', 1, [120, 1.7, 0.7], N, 1.5, 1.5);
D('carvingB', 1, [140, 1.7, -0.3], N, 1.5, 1.5);
D('sigil', 2, [131, 1.9, 0.3], S, 1.1, 1.1);
D('mural', 3, [112, 1.6, -0.6], N, 1.5, 0.8);
D('hands', 1, [104, 1.4, 0.5], S, 1.4, 0.7);
D('carving', 1, [110, 1.6, -7.6], N, 1.4, 1.4);
