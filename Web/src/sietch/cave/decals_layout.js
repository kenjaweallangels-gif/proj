D('sigil', 2, [132, 4.0, 18], E, 2.2, 2.2);

// ---------------------------------------------------------------- B5: зал ----
for (let i = 0; i < 8; i++) {
  const x = 154 + i * 6 + 3;
  for (const [sg, dir] of [[-1, N], [1, S]]) {
    D(i % 3 === 1 ? 'carvingB' : 'carving', 1, [x, 3.0, sg * 6], dir, 2.2, 2.2, { rot: ((i * 7) % 5 - 2) * 0.03, maxT: 22 });
    if (i % 2 === 0) D('sigil', 2, [x + 0.4, 5.9, sg * 6], dir, 2.0, 2.0, { maxT: 22 });
    else D('mural', 3, [x, 6.0, sg * 6], dir, 2.8, 1.4, { maxT: 22 });
  }
}
