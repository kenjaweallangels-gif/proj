/** [x, z, yWanted, k] — y будет прижат к потолку при запекании (потолок − 0.55). */
export function planGlobePositions() {
  const G = [];
  const add = (region, x, z, y, k = 1, extra = {}) => G.push({ region, x, z, y, k, ...extra });
  // B1: редкие, тусклые, под низким сводом.
  [5, 13, 18.5, 22, 28, 33, 38].forEach((x, i) => add('B1', x, (i % 2 ? 0.5 : -0.4) + (x > 24 ? 0.4 : 0), 2.5, 0.75));
  // B2: гроздья под высоким сводом, лампы в нишах под карнизом и на карнизе.
  for (let i = 0; i < 9; i++) {
    const x = 48 + i * 6;
    add('B2', x, ((i * 37) % 5 - 2) * 0.7, 8.3 - (i % 2) * 0.9, 1.15, { chain: 1 });
    if (i % 3 === 0) { add('B2', x + 0.7, 1.2, 9.4, 0.8); add('B2', x - 0.5, -1.0, 7.2, 0.7); }
  }
  for (const x of B2_ALCOVES.north) add('B2', x, -5.1, 2.6, 0.9);
  for (const x of B2_ALCOVES.south) add('B2', x, 5.1, 2.6, 0.9);
  for (let i = 0; i < 8; i++) { const x = 53 + i * 6; add('B2', x, i % 2 ? -6.3 : 6.3, 9.2, 0.9); }
  for (const x of SHELF_BAYS) { add('B2', x, -7.3, 8.3, 0.65); add('B2', x + 1, 7.3, 8.3, 0.65); }
  add('B2', 44, 0, 3.3, 0.85); add('B2', 45, 6, 4.5, 0.7); add('B2', 45, -6, 4.5, 0.7);
  // B3: у ниш и по проходам.
  for (let x = 102; x < 150; x += 6) add('B3', x, (Math.round(x) % 2 ? -0.4 : 0.4), 2.25, 0.8);
  for (const n of NICHES) add('B3', n.xc, n.side * 3.0, 1.9, n.open ? 0.9 : 0.55, { niche: n.id });
  for (let x = 104; x < 120; x += 6) { add('B3', x + 2, -7.5, 2.2, 0.65); add('B3', x + 2, 7.5, 2.2, 0.65); }
  add('B3', 118, -12, 2.2, 0.65); add('B3', 121, -15.2, 2.2, 0.65); add('B3', 128, -15, 2.2, 0.65); add('B3', 134, -14.8, 2.2, 0.65);
  add('B3', 140, -15, 1.9, 0.5);
  // B4: над водой и на карнизе.
  for (let i = 0; i < 3; i++) for (let j = 0; j < 2; j++) add('B4', 118 + i * 7, 13.5 + j * 9, 5.4 - (i + j) % 2 * 0.6, 1.0, { chain: 1 });
  add('B4', 122, 7.0, 2.1, 0.6); add('B4', 113.5, 18, 3.4, 0.7); add('B4', 136.5, 18, 3.4, 0.7);
  // B5: кольцо над ярусами, ниши, под сводом, над помостом.
  for (let i = 0; i < 14; i++) { const a = (i / 14) * Math.PI * 2 + 0.2; add('B5', HALL.cx + Math.cos(a) * 15.5, Math.sin(a) * 12.0, 3.9 + (i % 2) * 0.5, 1.15); }
  for (let i = 0; i < 7; i++) { const a = (i / 7) * Math.PI * 2 + 0.4; add('B5', HALL.cx + Math.cos(a) * 9.3, Math.sin(a) * 9.3, 12.0 + (i % 2) * 1.8, 0.9, { chain: 1 }); }
  add('B5', 153, -1.7, 2.4, 0.8); add('B5', 153, 1.7, 2.4, 0.8);
  for (const z of [-2.8, 0, 2.8]) add('B5', 193.5, z, 5.8 + (z === 0 ? 0.6 : 0), 1.2);
  add('B5', 197, -4, 5.0, 1.0); add('B5', 197, 4, 5.0, 1.0);
  return G;
}

