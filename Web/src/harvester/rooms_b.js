  dec(R, 'mural', [b.x0 + 0.02, y0 + 3.0, 8.0], '+x', 6.2, 3.6);
  dec(R, 'hands', [b.x0 + 0.02, y0 + 1.2, -2.0], '+x', 2.2, 1.5);
