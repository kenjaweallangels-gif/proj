/** Круглая колонна/ёмкость в схеме проходимости: крест из двух боксов (аппроксимация круга). */
function solidCyl(R, x, z, r, y0, y1) {
  const a = r * 0.62;
  R.plan.addBlock(x - r, y0, z - a, x + r, y1, z + a);
  R.plan.addBlock(x - a, y0, z - r, x + a, y1, z + r);
}

